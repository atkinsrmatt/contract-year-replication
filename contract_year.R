tost <- function(fit, term, bound) {
  b <- unname(fit$b[term]); se <- unname(fit$se[term])
  p_up <- stats::pt((b - bound) / se, fit$df)
  p_lo <- stats::pt((b + bound) / se, fit$df, lower.tail = FALSE)
  list(b = b, se = se, bound = bound, p = max(p_up, p_lo))
}

